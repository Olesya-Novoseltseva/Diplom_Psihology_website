import type { SurveyDefinition } from "./survey.types.js";

/**
 * Структура PSS-10 (Cohen et al.), шкала 0–4. Обратный подсчёт для позитивно сформулированных пунктов (№ 4, 5, 7, 8 в исходной нумерации).
 */
const PSS_LIKERT = ["Никогда", "Почти никогда", "Иногда", "Довольно часто", "Очень часто"];

/** Индексы (0-based) вопросов с обратным кодированием: было «уверенность / всё идёт по плану / контроль раздражений / всё под контролем». */
const PSS_REVERSE = new Set([3, 4, 6, 7]);

export const PSS10_SURVEY: SurveyDefinition = {
  key: "pss10",
  title: "PSS-10 (адаптированная шкала воспринимаемого стресса)",
  description:
    "За последний месяц, как часто вы испытывали следующее? Отметьте один ответ на каждый пункт.",
  sharedOptionLabels: PSS_LIKERT,
  scoreBandsHint:
    "Сумма после перекодирования: 0–13 обычно низкий стресс; 14–26 умеренный; 27–40 высокий воспринимаемый стресс (ориентир для самонаблюдения).",
  questions: [
    { id: "p1", text: "Беспокойство из‑за неожиданных событий", min: 0, max: 4 },
    { id: "p2", text: "Чувство, что важные вещи в жизни вы контролировать не можете", min: 0, max: 4 },
    { id: "p3", text: "Нервозность и стресс", min: 0, max: 4 },
    { id: "p4", text: "Уверенность в том, что справитесь с личными проблемами", min: 0, max: 4 },
    { id: "p5", text: "Чувство, что дела идут так, как вам нужно", min: 0, max: 4 },
    { id: "p6", text: "Чувство, что не успеваете справиться со всем, что должны сделать", min: 0, max: 4 },
    { id: "p7", text: "Способность держать раздражение под контролем", min: 0, max: 4 },
    { id: "p8", text: "Чувство, что вы держите ситуацию под контролем", min: 0, max: 4 },
    { id: "p9", text: "Злость из‑за того, что происходит не так, как хотелось", min: 0, max: 4 },
    { id: "p10", text: "Чувство, что трудности накапливаются так, что их уже не преодолеть", min: 0, max: 4 },
  ],
  score: (answers) => {
    let sum = 0;
    for (let i = 0; i < answers.length; i++) {
      const raw = answers[i]!;
      sum += PSS_REVERSE.has(i) ? 4 - raw : raw;
    }
    return sum;
  },
  interpret: (total) => {
    if (total <= 13) return "Относительно низкий воспринимаемый стресс. Регулярные паузы и сон помогут поддерживать уровень.";
    if (total <= 26)
      return "Умеренный уровень стресса. Пересмотрите нагрузку, делегирование и восстановление; при стабильности симптомов полезна беседа со специалистом.";
    return "Высокий воспринимаемый стресс. Имеет смысл снизить самотребования на время и обратиться за поддержкой вуза или очно.";
  },
};
